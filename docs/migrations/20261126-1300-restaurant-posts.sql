-- ============================================================
-- Les articles de blog d'un restaurant (ADR 0111)
--
-- Un ARTICLE DE BLOG est un texte que le restaurant publie dans son espace de commande
-- (/commander/<établissement>/articles). Ne pas le confondre avec un « article » de la carte (`menu_items`).
--
-- Quoi :
--   restaurant_posts        un article : établissement, adresse unique par établissement, langue, état
--                           (brouillon, en_ligne, retire, masque), version brouillon et version publiée
--                           (titre et blocs), origine (gérant ou Nina), confirmation des droits sur les
--                           photos (qui et quand), motif de masquage, auteur (effaçable).
--   restaurant_post_events  la trace : publié, retiré, masqué, démasqué, supprimé, signalé, refusé au
--                           contrôle (avec le motif), qui et quand. Aucune donnée sur un lecteur.
--   restaurant_post_daily   par article et par jour : lectures et appuis sur « Voir la carte », sans aucune
--                           donnée sur le lecteur.
--   bump_restaurant_post_daily()  ajoute 1 à l'un des deux compteurs (atomique).
--   stockage `restaurant-post-photos`  PRIVÉ : les photos ne s'affichent que par une adresse signée de courte
--                           durée. 2 Mo au plus, JPEG seul (le serveur réenregistre chaque photo, sans
--                           position GPS ni autre métadonnée).
--
-- Sécurité : RLS activée SANS policy = service role uniquement ; la fonction est refusée à `anon` et
--   `authenticated`. Aucune policy sur storage.objects pour ce bucket.
--
-- Sans cette migration : le bloc « Nos articles » n'apparaît pas côté client, les pages d'articles sont vides ou
--   introuvables, la console dit « pas encore activé ». Rien d'autre ne change, la commande n'en dépend pas.
--
-- Idempotente, non cassante. À APPLIQUER À LA MAIN dans l'éditeur SQL Supabase.
-- ============================================================

CREATE TABLE IF NOT EXISTS restaurant_posts (
  id                   UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id        TEXT         NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
  slug                 TEXT         NOT NULL CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(slug) <= 80),
  lang                 TEXT         NOT NULL DEFAULT 'fr' CHECK (lang IN ('fr', 'nl', 'en')),
  status               TEXT         NOT NULL DEFAULT 'brouillon' CHECK (status IN ('brouillon', 'en_ligne', 'retire', 'masque')),
  draft_title          TEXT         NOT NULL DEFAULT '' CHECK (char_length(draft_title) <= 80),
  draft_blocks         JSONB        NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(draft_blocks) = 'array'),
  -- Compte les versions du brouillon : « Oui, publier » ne publie que la version relue.
  revision             INTEGER      NOT NULL DEFAULT 1 CHECK (revision >= 1),
  published_title      TEXT         CHECK (published_title IS NULL OR char_length(published_title) BETWEEN 1 AND 80),
  published_blocks     JSONB        CHECK (published_blocks IS NULL OR jsonb_typeof(published_blocks) = 'array'),
  published_revision   INTEGER,
  origin               TEXT         NOT NULL DEFAULT 'gerant' CHECK (origin IN ('gerant', 'nina')),
  rights_confirmed_at  TIMESTAMPTZ,
  rights_confirmed_by  UUID,
  mask_reason          TEXT         CHECK (mask_reason IS NULL OR char_length(mask_reason) <= 300),
  masked_at            TIMESTAMPTZ,
  author_id            UUID         REFERENCES auth.users (id) ON DELETE SET NULL,
  created_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  first_published_at   TIMESTAMPTZ,
  published_at         TIMESTAMPTZ,
  withdrawn_at         TIMESTAMPTZ,
  -- Un article en ligne a toujours une version publiée.
  CONSTRAINT restaurant_posts_online_has_version
    CHECK (status <> 'en_ligne' OR (published_title IS NOT NULL AND published_blocks IS NOT NULL AND first_published_at IS NOT NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS restaurant_posts_slug_idx ON restaurant_posts (restaurant_id, slug);
CREATE INDEX IF NOT EXISTS restaurant_posts_online_idx ON restaurant_posts (restaurant_id, first_published_at DESC) WHERE status = 'en_ligne';
CREATE INDEX IF NOT EXISTS restaurant_posts_author_idx ON restaurant_posts (author_id) WHERE author_id IS NOT NULL;

ALTER TABLE restaurant_posts ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE restaurant_posts IS
  'Articles de blog d''un restaurant (ADR 0111). Brouillon et version publiée séparés ; service role uniquement.';

CREATE TABLE IF NOT EXISTS restaurant_post_events (
  id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- NULL après suppression de l'article : la trace (publié, retiré…) reste.
  post_id        UUID         REFERENCES restaurant_posts (id) ON DELETE SET NULL,
  restaurant_id  TEXT         NOT NULL,
  kind           TEXT         NOT NULL CHECK (kind IN ('publie', 'retire', 'masque', 'demasque', 'supprime', 'signale', 'refuse')),
  reason         TEXT         CHECK (reason IS NULL OR char_length(reason) <= 300),
  -- Qui (compte du gérant ou de la plateforme). Toujours NULL pour un signalement : rien sur le lecteur.
  actor_id       UUID,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS restaurant_post_events_restaurant_idx ON restaurant_post_events (restaurant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS restaurant_post_events_post_idx ON restaurant_post_events (post_id, kind);

ALTER TABLE restaurant_post_events ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS restaurant_post_daily (
  post_id     UUID     NOT NULL REFERENCES restaurant_posts (id) ON DELETE CASCADE,
  day         DATE     NOT NULL,
  reads       INTEGER  NOT NULL DEFAULT 0 CHECK (reads >= 0),
  menu_taps   INTEGER  NOT NULL DEFAULT 0 CHECK (menu_taps >= 0),
  PRIMARY KEY (post_id, day)
);

ALTER TABLE restaurant_post_daily ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION bump_restaurant_post_daily(p_post_id UUID, p_day DATE, p_kind TEXT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_kind NOT IN ('lecture', 'carte') THEN
    RAISE EXCEPTION 'compteur inconnu : %', p_kind;
  END IF;
  INSERT INTO restaurant_post_daily AS d (post_id, day, reads, menu_taps)
  VALUES (p_post_id, p_day, CASE WHEN p_kind = 'lecture' THEN 1 ELSE 0 END, CASE WHEN p_kind = 'carte' THEN 1 ELSE 0 END)
  ON CONFLICT (post_id, day) DO UPDATE
    SET reads = d.reads + EXCLUDED.reads, menu_taps = d.menu_taps + EXCLUDED.menu_taps;
END;
$$;

REVOKE ALL ON FUNCTION bump_restaurant_post_daily(UUID, DATE, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION bump_restaurant_post_daily(UUID, DATE, TEXT) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION bump_restaurant_post_daily(UUID, DATE, TEXT) TO service_role;

-- Espace de stockage PRIVÉ. `public = false` est reposé à chaque passage : ce bucket ne doit jamais devenir public.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('restaurant-post-photos', 'restaurant-post-photos', false, 2097152, ARRAY['image/jpeg'])
ON CONFLICT (id) DO UPDATE SET public = false, file_size_limit = 2097152, allowed_mime_types = ARRAY['image/jpeg'];
