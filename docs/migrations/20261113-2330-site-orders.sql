-- ============================================================
-- Les commandes du site (ADR 0099 §2 et §6, ADR 0100 §11)
--
-- Une COMMANDE DU SITE est passée par un client sur le site du restaurant : retrait au comptoir, paiement au comptoir
-- (ni paiement en ligne, ni livraison). Elle ne s'écrit JAMAIS dans `orders` (les tickets de caisse des membres, comptés
-- dans le programme) : vocabulaire et tables à part (ADR 0099 §6).
--
-- `site_orders` : une ligne par commande. `lines` est une PHOTO figée au moment de la commande (nom du plat, quantité, prix
-- de la ligne en centimes, choix lisibles, coin de cuisine) : un prix ou un nom changé plus tard ne réécrit pas une
-- commande passée. Le serveur recalcule tout (prix, choix) : le navigateur n'envoie jamais un prix.
-- `number` = numéro du jour pour l'établissement (« N° 0147 »), unique par jour.
-- Données personnelles : prénom et téléphone du client. Le restaurant est responsable du traitement, Boosteats son
-- sous-traitant ; une PURGE du téléphone et du prénom après quelques jours doit être branchée AVANT d'ouvrir le drapeau
-- à un vrai restaurant (ADR 0099, Conséquences). Jamais de croisement avec les membres sans consentement (ADR 0025).
--
-- `site_order_refusals` : une ligne par commande REFUSÉE (motif seulement, jamais de donnée du client), pour voir ce qui
-- bloque les clients (trace, ADR 0065) : limite par adresse, plat inconnu, choix invalide, restaurant fermé...
--
-- RLS activée SANS policy = service role uniquement. Idempotente, non cassante. Si elle n'est pas appliquée : la route de
-- commande répond « pas encore activé », la console le dit, rien ne casse. Le drapeau SITE_ORDER_RESTAURANTS (vide au
-- départ) garde toute la fonction fermée : sans lui, aucune route ne répond.
-- ============================================================

CREATE TABLE IF NOT EXISTS site_orders (
  id              UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  restaurant_id   TEXT         NOT NULL,
  order_day       DATE         NOT NULL,
  number          INTEGER      NOT NULL CHECK (number BETWEEN 1 AND 99999),
  first_name      TEXT         NOT NULL CHECK (char_length(first_name) BETWEEN 1 AND 24),
  phone           TEXT         CHECK (phone IS NULL OR char_length(phone) BETWEEN 6 AND 20),
  lines           JSONB        NOT NULL CHECK (jsonb_typeof(lines) = 'array'),
  total_cents     INTEGER      NOT NULL CHECK (total_cents >= 0),
  status          TEXT         NOT NULL DEFAULT 'recue' CHECK (status IN ('recue', 'prete', 'retiree', 'annulee')),
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  ready_at        TIMESTAMPTZ,
  picked_up_at    TIMESTAMPTZ,
  cancelled_at    TIMESTAMPTZ,
  cancel_reason   TEXT         CHECK (cancel_reason IS NULL OR char_length(cancel_reason) <= 200)
);

CREATE UNIQUE INDEX IF NOT EXISTS site_orders_number_day_idx ON site_orders (restaurant_id, order_day, number);
CREATE INDEX IF NOT EXISTS site_orders_restaurant_idx ON site_orders (restaurant_id, created_at DESC);

ALTER TABLE site_orders ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE site_orders IS
  'Commandes du site (retrait et paiement au comptoir). Jamais dans orders. lines = photo figée ; prénom et téléphone = données du client, à purger (ADR 0099).';

CREATE TABLE IF NOT EXISTS site_order_refusals (
  id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  TEXT         NOT NULL,
  reason         TEXT         NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 60),
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS site_order_refusals_restaurant_idx ON site_order_refusals (restaurant_id, created_at DESC);

ALTER TABLE site_order_refusals ENABLE ROW LEVEL SECURITY;
