-- ============================================================
-- Les allergènes d'un plat, et la trace de l'import du PDF (ADR 0100 §8)
--
-- Un allergène n'est JAMAIS un fait déduit : il vient du PDF du restaurateur ou de sa main, et il ne devient un fait que
-- quand il l'a CONFIRMÉ plat par plat.
--   allergens              NULL  = pas confirmé : le site dit « demande-nous au comptoir », jamais « aucun ».
--                          {}    = le restaurateur a confirmé qu'il n'y en a aucun.
--                          {…}   = les allergènes confirmés (liste fermée des 14 du règlement UE 1169/2011).
--   allergens_confirmed_at  quand il l'a confirmé (NULL tant que allergens est NULL).
--
-- Table `menu_pdf_imports` : une ligne par enregistrement d'un import de PDF (compteurs seulement, ni nom de plat, ni
-- texte du PDF, ni donnée personnelle) pour mesurer si la lecture est bonne : part des lignes rapprochées, des
-- descriptions gardées, des allergènes corrigés (docs/mesures/suivi-options-menu.sql, requêtes 7 et 8).
-- RLS activée SANS policy = service role uniquement.
--
-- Idempotente, non cassante. Si elle n'est pas appliquée, l'écran du PDF le dit et n'écrit rien (rien n'est perdu :
-- le restaurateur peut recommencer). À appliquer à la main dans l'éditeur SQL de Supabase dès la fusion.
-- ============================================================

ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergens              TEXT[];
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergens_confirmed_at TIMESTAMPTZ;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'menu_items_allergens_known') THEN
    ALTER TABLE menu_items ADD CONSTRAINT menu_items_allergens_known
      CHECK (allergens IS NULL OR allergens <@ ARRAY['gluten','crustaces','oeufs','poisson','arachides','soja','lait','coque','celeri','moutarde','sesame','sulfites','lupin','mollusques']::TEXT[]);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'menu_items_allergens_confirmed_together') THEN
    ALTER TABLE menu_items ADD CONSTRAINT menu_items_allergens_confirmed_together
      CHECK ((allergens IS NULL) = (allergens_confirmed_at IS NULL));
  END IF;
END $$;

COMMENT ON COLUMN menu_items.allergens IS
  'Allergènes CONFIRMES par le restaurateur (14 du règlement UE 1169/2011). NULL = pas confirmé (« demande-nous au comptoir »), {} = aucun, confirmé.';
COMMENT ON COLUMN menu_items.allergens_confirmed_at IS
  'Quand le restaurateur a confirmé la liste d''allergènes de ce plat.';

CREATE TABLE IF NOT EXISTS menu_pdf_imports (
  id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id       TEXT         NOT NULL,
  created_by          TEXT,
  created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  lines_read          INTEGER      NOT NULL DEFAULT 0 CHECK (lines_read >= 0),
  matched             INTEGER      NOT NULL DEFAULT 0 CHECK (matched >= 0),
  matched_near        INTEGER      NOT NULL DEFAULT 0 CHECK (matched_near >= 0),
  unmatched           INTEGER      NOT NULL DEFAULT 0 CHECK (unmatched >= 0),
  articles_without    INTEGER      NOT NULL DEFAULT 0 CHECK (articles_without >= 0),
  desc_proposed       INTEGER      NOT NULL DEFAULT 0 CHECK (desc_proposed >= 0),
  desc_kept           INTEGER      NOT NULL DEFAULT 0 CHECK (desc_kept >= 0),
  desc_edited         INTEGER      NOT NULL DEFAULT 0 CHECK (desc_edited >= 0),
  allergens_proposed  INTEGER      NOT NULL DEFAULT 0 CHECK (allergens_proposed >= 0),
  allergens_changed   INTEGER      NOT NULL DEFAULT 0 CHECK (allergens_changed >= 0),
  allergens_confirmed INTEGER      NOT NULL DEFAULT 0 CHECK (allergens_confirmed >= 0),
  rows_written        INTEGER      NOT NULL DEFAULT 0 CHECK (rows_written >= 0)
);

CREATE INDEX IF NOT EXISTS menu_pdf_imports_restaurant_idx ON menu_pdf_imports (restaurant_id, created_at DESC);

ALTER TABLE menu_pdf_imports ENABLE ROW LEVEL SECURITY;
