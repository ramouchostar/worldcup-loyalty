-- ============================================================
-- Le coin de cuisine d'un plat, et la trace de son réglage (ADR 0100 §9)
--
-- `menu_items.kitchen_zone` : où se prépare le plat (« Pizza », « Pâtes », « Grill », « Comptoir »…), texte libre de
-- 30 lettres au plus choisi par le restaurateur. NULL = pas de coin : le plat sort sur le ticket « CUISINE », jamais perdu.
-- Il sert à découper le ticket de cuisine en un ticket par coin (lib/menu-options/tickets.ts). Rien n'est imprimé
-- aujourd'hui : il n'existe ni commande du site ni imprimante (ADR 0099 §5).
--
-- `menu_zone_setups` : une ligne par enregistrement des coins, des compteurs seulement (combien de plats, combien de
-- coins, combien de nos propositions gardées ou changées), pour mesurer si notre proposition d'après la famille du plat
-- est bonne (docs/mesures/suivi-options-menu.sql, requête 9). RLS activée SANS policy = service role uniquement.
--
-- Idempotente, non cassante. Si elle n'est pas appliquée, l'écran des coins le dit et n'écrit rien. À appliquer à la main
-- dans l'éditeur SQL de Supabase dès la fusion (docs/migrations/README.md).
-- ============================================================

ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS kitchen_zone TEXT;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'menu_items_kitchen_zone_length') THEN
    ALTER TABLE menu_items ADD CONSTRAINT menu_items_kitchen_zone_length
      CHECK (kitchen_zone IS NULL OR (char_length(kitchen_zone) BETWEEN 1 AND 30));
  END IF;
END $$;

COMMENT ON COLUMN menu_items.kitchen_zone IS
  'Coin de cuisine du plat (30 lettres au plus), choisi par le restaurateur. NULL = ticket « CUISINE ».';

CREATE TABLE IF NOT EXISTS menu_zone_setups (
  id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  TEXT         NOT NULL,
  created_by     TEXT,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  articles       INTEGER      NOT NULL DEFAULT 0 CHECK (articles >= 0),
  zones          INTEGER      NOT NULL DEFAULT 0 CHECK (zones >= 0),
  suggested      INTEGER      NOT NULL DEFAULT 0 CHECK (suggested >= 0),
  suggested_kept INTEGER      NOT NULL DEFAULT 0 CHECK (suggested_kept >= 0),
  changed        INTEGER      NOT NULL DEFAULT 0 CHECK (changed >= 0),
  cleared        INTEGER      NOT NULL DEFAULT 0 CHECK (cleared >= 0)
);

CREATE INDEX IF NOT EXISTS menu_zone_setups_restaurant_idx ON menu_zone_setups (restaurant_id, created_at DESC);

ALTER TABLE menu_zone_setups ENABLE ROW LEVEL SECURITY;
