-- ============================================================
-- La trace de l'écran « Options de mes plats » (ADR 0100, ADR 0065)
--
-- À chaque enregistrement, une ligne : combien de plats, combien de groupes de plats, combien de nos choix proposés
-- le restaurateur a GARDÉS, combien de lignes il a changées, combien de plats proposés il a gardés ou ajoutés.
-- C'est le chiffre qui dira que la règle est fausse : si la part des choix gardés est basse pour une famille, nos
-- propositions pour cette famille ne valent rien. `detail` garde un objet par groupe de plats enregistré
-- (famille, confiance, plats, choix proposés / gardés / ajoutés, lignes changées, prix mis).
--
-- Aucune donnée personnelle ni prix : des compteurs. RLS activée SANS policy = service role uniquement.
-- Idempotente. Si la table n'existe pas encore, l'écran enregistre quand même les options et le dit dans les
-- journaux (lib/menu-options/save.ts) : la trace est perdue pour cet enregistrement, jamais le travail du restaurateur.
-- Requêtes de suivi : docs/mesures/suivi-options-menu.sql. À appliquer à la main dans l'éditeur SQL de Supabase
-- dès la fusion (docs/migrations/README.md).
-- ============================================================

CREATE TABLE IF NOT EXISTS menu_option_setups (
  id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id     TEXT         NOT NULL,
  created_by        TEXT,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  articles_total    INTEGER      NOT NULL DEFAULT 0 CHECK (articles_total >= 0),
  lots_total        INTEGER      NOT NULL DEFAULT 0 CHECK (lots_total >= 0),
  lots_saved        INTEGER      NOT NULL DEFAULT 0 CHECK (lots_saved >= 0),
  unplaced          INTEGER      NOT NULL DEFAULT 0 CHECK (unplaced >= 0),
  suggested         INTEGER      NOT NULL DEFAULT 0 CHECK (suggested >= 0),
  suggested_kept    INTEGER      NOT NULL DEFAULT 0 CHECK (suggested_kept >= 0),
  dishes_added      INTEGER      NOT NULL DEFAULT 0 CHECK (dishes_added >= 0),
  merges            INTEGER      NOT NULL DEFAULT 0 CHECK (merges >= 0),
  splits            INTEGER      NOT NULL DEFAULT 0 CHECK (splits >= 0),
  choices_proposed  INTEGER      NOT NULL DEFAULT 0 CHECK (choices_proposed >= 0),
  choices_kept      INTEGER      NOT NULL DEFAULT 0 CHECK (choices_kept >= 0),
  lines_changed     INTEGER      NOT NULL DEFAULT 0 CHECK (lines_changed >= 0),
  prices_set        INTEGER      NOT NULL DEFAULT 0 CHECK (prices_set >= 0),
  detail            JSONB        NOT NULL DEFAULT '[]'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_menu_option_setups_restaurant ON menu_option_setups (restaurant_id, created_at DESC);

ALTER TABLE menu_option_setups ENABLE ROW LEVEL SECURITY;
